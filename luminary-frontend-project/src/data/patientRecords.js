/** Proportion of required fields captured — drives the completeness meter. */
export function recordCompleteness(record) {
  if (!record) return { captured: 0, total: REQUIRED_FIELDS.length, percent: 0, missing: [] };
  const missing = REQUIRED_FIELDS.filter((field) => {
    const value = record[field.key];
    if (typeof value === 'boolean') return value !== true;
    return value === undefined || value === null || String(value).trim() === '' || String(value) === '—' || String(value) === 'Not recorded';
  });
  const captured = REQUIRED_FIELDS.length - missing.length;
  return {
    captured,
    total: REQUIRED_FIELDS.length,
    percent: Math.round((captured / REQUIRED_FIELDS.length) * 100),
    missing,
  };
}

